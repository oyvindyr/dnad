    pure function chain_duals__d_a_c(fy, yx) result(fx)
        !! Convert a function value from type(dual__a_t) to type(dual__c_t)
        !! by applying the chain rule of derivation. Second input yx(:) has type(dual__c_t)
        !! and represents the design variables by which the derivatives of fy is taken with respect to.
        !! Thus, size(yx) needs to be equal to size(fy%g) (size known at compile time).
         
        ! This function has been automatically generated by dnad_chain_duals.fypp
        type(dual__a_t), intent(in) :: fy
        type(dual__c_t), intent(in) :: yx(:)
        type(dual__c_t) :: fx
        
        integer :: p, j

        fx%f = fy%f
        fx%g = 0
        do p = 1, size(fy%g)
            do j = 1, size(fx%g)
                fx%g(j) = fx%g(j) + fy%g(p)*yx(p)%g(j)
            end do
        end do

    end function
    pure function chain_duals__hd_a_c(fy, yx) result(fx)
        !! Convert a function value from type(hdual__a_t) to type(hdual__c_t)
        !! by applying the chain rule of derivation. Second input yx(:) has type(hdual__c_t)
        !! and represents the design variables by which the derivatives of fy is taken with respect to.
        !! Thus, size(yx) needs to be equal to size(fy%d%g) (size known at compile time).
         
        ! This function has been automatically generated by dnad_chain_duals.fypp
        type(hdual__a_t), intent(in) :: fy
        type(hdual__c_t), intent(in) :: yx(:)
        type(hdual__c_t) :: fx
        
        integer :: p, j
        integer :: i, q, k, nk
        real(dp) :: hfy(size(fy%d%g), size(fy%d%g))
        real(dp) :: tmp

        ! Calculate dual part
        fx%d%f = fy%d%f
        fx%d%g = 0
        do p = 1, size(fy%d%g)
            do j = 1, size(fx%d%g)
                fx%d%g(j) = fx%d%g(j) + fy%d%g(p)*yx(p)%d%g(j)
            end do
        end do

        ! Calculate hessian part
        nk = size(fx%d%g)*(size(fx%d%g)+1)/2
        fx%h = 0
        do p = 1, size(fy%d%g)
            do k = 1, nk
                fx%h(k) = fx%h(k) + fy%d%g(p)*yx(p)%h(k)
            end do
        end do
        hfy = hessian(fy)
        do q = 1, size(fy%d%g)
            do p = 1, size(fy%d%g)
                k = 0
                do j = 1, size(fx%d%g)
                    tmp = hfy(p,q)*yx(q)%d%g(j)
                    do i = j, size(fx%d%g)
                        k = k + 1
                        fx%h(k) = fx%h(k) + tmp*yx(p)%d%g(i)
                    end do
                end do
            end do
        end do

    end function
