def test_module(config, cases):
    chks = ', '.join(['chk_r', 'chk_r1', 'chk_r2', 'chk_i', 'chk_l'] + [f'chk_{p}{k}' for k in NDERIV for p in ('d', 'hd')])
    lines = f'''module test_all_{config}_mod
    !! Generated by gen_tests.py. Every specific of dnad_all_{config}_mod, called through its generic, against
    !! reference values from sympy.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    use, intrinsic :: ieee_arithmetic, only: ieee_value, ieee_quiet_nan, ieee_is_nan
    use dnad_all_{config}_mod
    implicit none
    private

    public test_all_{config}

    real(dp), parameter :: rtol = 1.0e-12_dp
    real(dp) :: nan
    integer :: nfail = 0

    interface chk
        module procedure {chks}
    end interface

contains

    function test_all_{config}() result(is_ok)
        logical :: is_ok
        nan = ieee_value(nan, ieee_quiet_nan)
        nfail = 0
        call run()
        is_ok = nfail == 0
        if (is_ok) then
            print '(a)', 'test_all_{config}: ok'
        else
            print '(a, i0, a)', 'test_all_{config}: ', nfail, ' failed'
        end if
    end function

    subroutine compare(name, x, ref)
        character(*), intent(in) :: name
        real(dp), intent(in) :: x(:), ref(:)
        integer :: i
        do i = 1, size(ref)
            if (ieee_is_nan(ref(i))) then
                if (ieee_is_nan(x(i))) cycle
            else if (abs(x(i) - ref(i)) <= rtol*max(1.0_dp, abs(ref(i)))) then
                cycle
            end if
            nfail = nfail + 1
            print '(a, a, i0, a, es24.16, a, es24.16)', name, '(', i, '): ', x(i), ' /= ', ref(i)
        end do
    end subroutine

    subroutine chk_r(name, x, ref)
        character(*), intent(in) :: name
        real(dp), intent(in) :: x, ref
        call compare(name, [x], [ref])
    end subroutine

    subroutine chk_r1(name, x, ref)
        character(*), intent(in) :: name
        real(dp), intent(in) :: x(:), ref(:)
        call compare(name, x, ref)
    end subroutine

    subroutine chk_r2(name, x, ref)
        character(*), intent(in) :: name
        real(dp), intent(in) :: x(:, :), ref(:, :)
        call compare(name, reshape(x, [size(x)]), reshape(ref, [size(ref)]))
    end subroutine

    subroutine chk_i(name, x, ref)
        character(*), intent(in) :: name
        integer, intent(in) :: x, ref
        if (x /= ref) then
            nfail = nfail + 1
            print '(a, a, i0, a, i0)', name, ': ', x, ' /= ', ref
        end if
    end subroutine

    subroutine chk_l(name, x, ref)
        character(*), intent(in) :: name
        logical, intent(in) :: x, ref
        if (x .neqv. ref) then
            nfail = nfail + 1
            print '(a, a, l1, a, l1)', name, ': ', x, ' /= ', ref
        end if
    end subroutine
'''.split('\n')
    lines += helpers()
    lines += ['', '    subroutine run()']
    for case in cases:
        lines += case.lines()
    lines += ['    end subroutine', '', 'end module', '']
    return '\n'.join(lines)


def generate(config, stringent):
    source = dnad_module(config, stringent)
    ifaces = interfaces(source)
    rng = random.Random(f'dnad-{config}')
    cases = []
    for iface, specifics in ifaces.items():
        if iface in ELEMENTAL:
            cases += elemental_cases(iface, specifics, rng)
        elif iface not in SPECIAL:
            raise KeyError(f'no test for interface {iface}')
    cases += assignment_cases(rng) + array_cases(rng) + getter_cases(rng) + jacobi_cases(rng)
    cases += initialize_cases(rng) + chain_cases(rng)
    if stringent:
        cases += stringent_cases(ifaces, rng)

    reached = set().union(*(c.specifics for c in cases))
    expected = procedures(source) - {'set_NaN'}
    missing = expected - reached
    if missing:
        raise RuntimeError(f'{config}: no check reaches ' + ', '.join(sorted(missing)))
    unknown = reached - expected
    if unknown:
        raise RuntimeError(f'{config}: checks name procedures that do not exist: ' + ', '.join(sorted(unknown)))

    for name, text in [(f'dnad_all_{config}_mod.f90', source), (f'test_all_{config}_mod.f90', test_module(config, cases))]:
        with open(os.path.join(HERE, name), 'w', newline='\n') as f:
            f.write(text)
    print(f'{config}: {len(cases)} checks over {len(expected)} procedures')


if __name__ == '__main__':
    for config, stringent in CONFIGS.items():
        generate(config, stringent)
