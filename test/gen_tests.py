''' Generate a test of every procedure the dnad module macros emit, with reference values from sympy.

For each configuration (stringent or not) this writes
    test/dnad_all_<config>_mod.f90   dnad_module_spec/impl with all interfaces, for three kinds
    test/test_all_<config>_mod.f90   one or more checks per specific, each called through its generic

The specifics are read from the generated module, and generation fails if one has no check. A dual input is a
second-order Taylor polynomial u(x) = f + g.x + 1/2 x'Hx; the reference result is F(u(x), ...) differentiated
at x = 0 by the chain rule, with F's partial derivatives from sympy.

    uv run --group dev python test/gen_tests.py
'''
import math
import os
import random
import re

import fypp
import sympy as sp

import dnad

HERE = os.path.dirname(os.path.abspath(__file__))
NDERIV = {'a': 3, 'b': 2, 'c': 3}
KINDS = "[dnad.Kind('a', 3, hyper=True), dnad.Kind('b', 2, hyper=True, unroll=True), dnad.Kind('c', 3, hyper=True, unroll=True)]"
CHAINS = [('a', 'c')]  # (y, x): both hyper
CONFIGS = {'stringent': True, 'lenient': False}
PREC = 40


# ---------------------------------------------------------------------------------------------------------------
# The module under test and its inventory

def dnad_module(config, stringent):
    chains = '[' + ', '.join(f'(k_{y}, k_{x})' for y, x in CHAINS) + ']'
    src = (f"#:include 'dnad_module.fypp'\n#:include 'dnad_dual_types.fypp'\n"
           f"#:set kinds = {KINDS}\n"
           f"#:set k_a, k_b, k_c = kinds\n"
           f"#:set config = dnad.Config('dp', stringent={stringent})\n"
           f"module dnad_all_{config}_mod\n"
           f"    !! Generated by gen_tests.py: everything dnad_module_spec/impl emit\n"
           f"    use, intrinsic :: iso_fortran_env, only: dp => real64\n    implicit none\n"
           f"  #:for k in kinds\n    $:dnad_dual_type(k, 'dp', k.nderiv)\n  #:endfor\n"
           f"    $:dnad_module_spec(kinds, config, None, {chains})\n"
           f"contains\n"
           f"    $:dnad_module_impl(kinds, config, None, {chains})\n"
           f"end module\n")
    options = fypp.FyppOptions()
    options.modules = ['dnad']
    options.includes = dnad.include_dirs()
    return fypp.Fypp(options).process_text(src)


def interfaces(source):
    ''' interface name -> its specifics, in order '''
    spec = source.split('\ncontains\n', 1)[0]
    return {m.group(1).strip(): re.findall(r'module procedure\s+(\w+)', m.group(2))
            for m in re.finditer(r'^\s*interface\s+(.+?)\s*\n(.*?)^\s*end interface', spec, re.M | re.S)}


def procedures(source):
    impl = source.split('\ncontains\n', 1)[1]
    return set(re.findall(r'^[ \t]*(?:(?:impure\s+|pure\s+)?elemental\s+|pure\s+)?(?:function|subroutine)\s+(\w+)\(',
                          impl, re.M))


