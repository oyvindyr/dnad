# Elemental scalar procedures: the argument types come from the specific's name

def arg_types(specific):
    types = specific.split('__', 1)[1].split('_')
    return types * 2 if specific.startswith('atan2__') else types  # atan2__da(u, v)


def pos(rng, t, i):
    return rng.uniform(0.5, 2.0)


def unit(rng, t, i):
    return rng.uniform(-0.8, 0.8)


def ints(*values):
    ''' A domain giving the i-th listed value to an integer argument, and a positive value otherwise '''
    def dom(rng, t, i):
        return values[i % len(values)] if t == 'i' else pos(rng, t, i)
    return dom


def fixed(*values):
    ''' The i-th argument's value is values[i], as an integer for an integer argument '''
    def dom(rng, t, i):
        return int(values[i]) if t == 'i' else float(values[i])
    return dom


def branch(take_first):
    ''' max/min-like: the result is the first or the second argument, as the dual type '''
    def F(a):
        pick = a[0] if take_first(a[0].f, a[1].f) else a[1]
        out = next(x.t for x in a if x.dual)
        return pick if pick.dual else const(pick.t, pick.f, out)
    return F


def unary_or_binary(f1, f2):
    return lambda a: smooth(f1 if len(a) == 1 else f2, a)


def compare(op):
    return lambda a: Val('l', op(a[0].f, a[1].f))


def abs_(a):
    s = 1 if a[0].f > 0 else -1
    return smooth(lambda x: s * x, a)


def sign_(a):
    s = 1 if a[1].f >= 0 else -1
    v1 = a[0]
    if not v1.dual:
        return const('r', s * abs(v1.f), a[1].t)
    t = 1 if v1.f > 0 else -1
    return smooth(lambda x, y: s * t * x, a)


def nint(x):
    return int(math.copysign(math.floor(abs(x) + 0.5), x))


ORDER3 = [fixed(1, 2), fixed(2, 2), fixed(2, 1)]  # less, equal, greater
TWO_WAYS = [fixed(2, 1), fixed(1, 2)]

# interface -> (call format by arity, reference F(list of Val), domains: one case per entry)
ELEMENTAL = {
    'operator (+)': (('+{0}', '{0} + {1}'), unary_or_binary(lambda x: x, lambda x, y: x + y), [ints(2, 3)]),
    'operator (-)': (('-{0}', '{0} - {1}'), unary_or_binary(lambda x: -x, lambda x, y: x - y), [ints(2, 3)]),
    'operator (*)': ((None, '{0}*{1}'), lambda a: smooth(lambda x, y: x * y, a), [ints(2, 3)]),
    'operator (/)': ((None, '{0}/{1}'), lambda a: smooth(lambda x, y: x / y, a), [ints(2, 3)]),
    'operator (**)': ((None, '{0}**{1}'), lambda a: smooth(lambda x, y: x ** y, a), [ints(3), ints(-2)]),
    'operator (==)': ((None, '{0} == {1}'), compare(lambda x, y: x == y), ORDER3),
    'operator (/=)': ((None, '{0} /= {1}'), compare(lambda x, y: x != y), ORDER3),
    'operator (<)': ((None, '{0} < {1}'), compare(lambda x, y: x < y), ORDER3),
    'operator (<=)': ((None, '{0} <= {1}'), compare(lambda x, y: x <= y), ORDER3),
    'operator (>)': ((None, '{0} > {1}'), compare(lambda x, y: x > y), ORDER3),
    'operator (>=)': ((None, '{0} >= {1}'), compare(lambda x, y: x >= y), ORDER3),
    'abs': (('abs({0})',), abs_, [fixed(1.3), fixed(-1.3)]),
    'dabs': (('dabs({0})',), abs_, [fixed(1.3), fixed(-1.3)]),
    'acos': (('acos({0})',), lambda a: smooth(sp.acos, a), [unit]),
    'asin': (('asin({0})',), lambda a: smooth(sp.asin, a), [unit]),
    'atan': (('atan({0})',), lambda a: smooth(sp.atan, a), [unit]),
    'atan2': ((None, 'atan2({0}, {1})'), lambda a: smooth(sp.atan2, a), [pos, fixed(-0.7, -1.2)]),
    'cos': (('cos({0})',), lambda a: smooth(sp.cos, a), [pos]),
    'dcos': (('dcos({0})',), lambda a: smooth(sp.cos, a), [pos]),
    'sin': (('sin({0})',), lambda a: smooth(sp.sin, a), [pos]),
    'dsin': (('dsin({0})',), lambda a: smooth(sp.sin, a), [pos]),
    'tan': (('tan({0})',), lambda a: smooth(sp.tan, a), [unit]),
    'dtan': (('dtan({0})',), lambda a: smooth(sp.tan, a), [unit]),
    'exp': (('exp({0})',), lambda a: smooth(sp.exp, a), [pos]),
    'log': (('log({0})',), lambda a: smooth(sp.log, a), [pos]),
    'log10': (('log10({0})',), lambda a: smooth(lambda x: sp.log(x, 10), a), [pos]),
    'sqrt': (('sqrt({0})',), lambda a: smooth(sp.sqrt, a), [pos]),
    'hypot': ((None, 'hypot({0}, {1})'), lambda a: smooth(lambda x, y: sp.sqrt(x ** 2 + y ** 2), a), [pos]),
    'int': (('int({0})',), lambda a: Val('i', int(a[0].f)), [fixed(-2.7), fixed(2.7)]),
    'nint': (('nint({0})',), lambda a: Val('i', nint(a[0].f)), [fixed(-2.7), fixed(2.5)]),
    'max': ((None, 'max({0}, {1})'), branch(lambda x, y: x > y), TWO_WAYS),
    'min': ((None, 'min({0}, {1})'), branch(lambda x, y: x < y), TWO_WAYS),
    'dmax1': ((None, 'dmax1({0}, {1})'), branch(lambda x, y: x > y), TWO_WAYS),
    'dmin1': ((None, 'dmin1({0}, {1})'), branch(lambda x, y: x < y), TWO_WAYS),
    'sign': ((None, 'sign({0}, {1})'), sign_, [fixed(1.3, 0.7), fixed(-1.3, -0.7)]),
}


def elemental_cases(iface, specifics, rng):
    fmts, F, domains = ELEMENTAL[iface]
    cases = []
    for specific in specifics:
        types = arg_types(specific)
        fmt = fmts[len(types) - 1]
        for dom in domains:
            args = [rand_val(rng, t, dom(rng, t, i)) for i, t in enumerate(types)]
            ref = F(args)
            names = [f'x{i}' for i in range(len(args))]
            decls = [f'{ftype(a.t)} :: {nm}' for a, nm in zip(args, names) if a.dual]
            body = [f'{nm} = {expr(a)}' for a, nm in zip(args, names) if a.dual]
            call = fmt.format(*[nm if a.dual else expr(a) for a, nm in zip(args, names)])
            body.append(check(specific, call, ref))
            cases.append(Case(specific, decls, body))
    return cases


def stringent_cases(ifaces, rng):
    ''' Points where the derivative does not exist: NaN where the result depends on it '''
    cases = []
    for t in kinds_types(hyper=True):
        n = n_of(t)
        g = [0.0] + [0.5] * (n - 1)
        nan_g = [0.0] + [math.nan] * (n - 1)
        x = Val(t, 0.0, g, [[0.0] * n for _ in range(n)] if t.startswith('hd') else None)
        if f'sqrt__{t}' in ifaces['sqrt']:
            ref = Val(t, 0.0, nan_g, [[math.nan] * n for _ in range(n)] if x.hyper else None)
            cases.append(Case(f'sqrt__{t}', [f'{ftype(t)} :: x'], [f'x = {expr(x)}', check(f'sqrt__{t}', 'sqrt(x)', ref)]))
        if not x.hyper:
            cases.append(Case(f'abs__{t}', [f'{ftype(t)} :: x'],
                              [f'x = {expr(x)}', check(f'abs__{t}', 'abs(x)', Val(t, 0.0, nan_g))]))
            for fun, f0, val in [('acos', 1.0, 0.0), ('acos', -1.0, math.pi), ('asin', 1.0, math.pi / 2),
                                 ('asin', -1.0, -math.pi / 2)]:
                y = rand_val(rng, t, f0)
                cases.append(Case(f'{fun}__{t}', [f'{ftype(t)} :: x'],
                                  [f'x = {expr(y)}', check(f'{fun}__{t}', f'{fun}(x)', Val(t, val, [math.nan] * n))]))
    return cases


