# Fortran text

def lit(x):
    if isinstance(x, bool):
        return '.true.' if x else '.false.'
    if isinstance(x, int):
        return f'({x})' if x < 0 else str(x)
    if math.isnan(x):
        return 'nan'
    s = f'{x:.17e}_dp'
    return f'({s})' if x < 0 else s


def arr(xs):
    return '[' + ', '.join(lit(x) for x in xs) + ']'


def expr(v):
    ''' A Fortran expression for the value v '''
    if not v.dual:
        return lit(v.f if v.t != 'i' else int(v.f))
    if v.hyper:
        return f'mk_{v.t}({lit(v.f)}, {arr(v.g)}, {arr(packed(v.H))})'
    return f'mk_{v.t}({lit(v.f)}, {arr(v.g)})'


def ftype(t):
    if t == 'r':
        return 'real(dp)'
    if t == 'i':
        return 'integer'
    if t == 'l':
        return 'logical'
    return f"type({'hdual' if t.startswith('hd') else 'dual'}__{t[-1]}_t)"


def check(name, x, ref):
    ''' call chk on the Fortran expression x against the reference value ref '''
    if ref.t in ('r', 'i', 'l'):
        return f"call chk('{name}', {x}, {lit(ref.f)})"
    if ref.hyper:
        return f"call chk('{name}', {x}, {lit(ref.f)}, {arr(ref.g)}, {arr(packed(ref.H))})"
    return f"call chk('{name}', {x}, {lit(ref.f)}, {arr(ref.g)})"


def wrap(line, width=120):
    ''' Split a long line at ', ' with Fortran continuations '''
    if len(line) <= width:
        return [line]
    indent = line[:len(line) - len(line.lstrip())] + '        '
    out, cur = [], ''
    for part in re.split(r'(?<=, )', line):
        if cur and len(cur) + len(part) > width:
            out.append(cur + '&')
            cur = indent + part
        else:
            cur += part
    out.append(cur)
    return out


class Case:
    ''' One block of the test: locals, statements, and the specifics it is meant to reach '''

    def __init__(self, specifics, decls=(), body=()):
        self.specifics = set([specifics] if isinstance(specifics, str) else specifics)
        self.decls, self.body = list(decls), list(body)

    def lines(self):
        out = ['        block']
        out += [f'            {d}' for d in self.decls]
        out += [f'            {b}' for b in self.body]
        out.append('        end block')
        return [w for line in out for w in wrap(line)]


