# Values and the reference

class Val:
    ''' A test value of type t: 'r', 'i', 'l', 'd<kind>' (dual) or 'hd<kind>' (hyper-dual) '''

    def __init__(self, t, f, g=None, H=None):
        self.t, self.f = t, f
        self.g: list = g if g is not None else []
        self.H: list = H if H is not None else []

    @property
    def dual(self):
        return self.t not in ('r', 'i', 'l')

    @property
    def hyper(self):
        return self.t.startswith('hd')


def n_of(t):
    return NDERIV[t[-1]]


def rand_val(rng, t, f):
    if t == 'i':
        return Val(t, int(round(f)))
    if t == 'r':
        return Val(t, f)
    n = n_of(t)
    g = [rng.uniform(-1, 1) for _ in range(n)]
    H = None
    if t.startswith('hd'):
        H = [[0.0] * n for _ in range(n)]
        for j in range(n):
            for i in range(j, n):
                H[i][j] = H[j][i] = rng.uniform(-1, 1)
    return Val(t, f, g, H)


def const(t, f, n_t):
    ''' A real or integer f as the dual type n_t: zero derivatives '''
    n = n_of(n_t)
    return Val(n_t, float(f), [0.0] * n, [[0.0] * n for _ in range(n)] if n_t.startswith('hd') else None)


def smooth(fn, args, out=None):
    ''' F = fn(args) for a twice differentiable fn, by the chain rule over the dual arguments '''
    syms = [sp.Symbol(f's{i}', real=True) for i in range(len(args))]
    ins = [syms[i] if a.dual else (sp.Integer(a.f) if a.t == 'i' else sp.Float(a.f, PREC)) for i, a in enumerate(args)]
    expr = fn(*ins)
    duals = [i for i, a in enumerate(args) if a.dual]
    out = out or args[duals[0]].t
    point = {syms[i]: sp.Float(args[i].f, PREC) for i in duals}

    def ev(e):
        return float(sp.N(sp.sympify(e).subs(point), PREC))

    n = n_of(out)
    d1 = {i: sp.diff(expr, syms[i]) for i in duals}
    e1 = {i: ev(d1[i]) for i in duals}
    g = [sum(e1[i] * args[i].g[p] for i in duals) for p in range(n)]
    H = None
    if out.startswith('hd'):
        e2 = {(i, j): ev(sp.diff(d1[i], syms[j])) for i in duals for j in duals}
        H = [[sum(e1[i] * args[i].H[p][q] for i in duals)
              + sum(e2[i, j] * args[i].g[p] * args[j].g[q] for i in duals for j in duals)
              for q in range(n)] for p in range(n)]
    return Val(out, ev(expr), g, H)


def packed(H):
    n = len(H)
    return [H[i][j] for j in range(n) for i in range(j, n)]


