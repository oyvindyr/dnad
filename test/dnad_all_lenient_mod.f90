                fx%h(k) = fx%h(k) + fy%d%g(p)*yx(p)%h(k)
            end do
        end do
        hfy = hessian(fy)
        do q = 1, size(fy%d%g)
            do p = 1, size(fy%d%g)
                k = 0
                do j = 1, size(fx%d%g)
                    tmp = hfy(p,q)*yx(q)%d%g(j)
                    do i = j, size(fx%d%g)
                        k = k + 1
                        fx%h(k) = fx%h(k) + tmp*yx(p)%d%g(i)
                    end do
                end do
            end do
        end do

    end function
